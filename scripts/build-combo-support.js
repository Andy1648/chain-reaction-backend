// scripts/build-combo-support.js — BUILD-TIME. Run it, commit comboSupport.json.
//
// Nothing here runs in the game: gameLogic.js reads the committed table, so the weighting can
// never depend on reading a word list at request time.
//
//   node scripts/build-combo-support.js          write comboSupport.json
//   node scripts/build-combo-support.js --dry    report only
//
// SUPPORT = how many of the 3,000 commonest English words (data/top3k.txt) CONTAIN the combo.
// That is the same test a player has to satisfy, against the vocabulary a player actually has,
// so it measures the thing that decides whether a turn is answerable at all.
//
// The old model weighted combos by LENGTH (plus a pool-size bonus computed against the ~18k
// botWords corpus). Length is uncorrelated with whether answers exist in a player's head:
// "kle" is three letters and sits in ZERO of the top 3000; "ion" is three letters and sits in
// dozens. This table is what replaces that guess with a measurement.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const { ALL_COMBOS: COMBOS } = require(path.join(ROOT, 'gameLogic.js'));

const MIN_SUPPORT = 5; // a combo with fewer than this many common words is a dead end

function readTop3k() {
  const raw = fs.readFileSync(path.join(ROOT, 'data', 'top3k.txt'), 'utf8');
  return raw
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter((w) => w && !w.startsWith('#'));
}

const words = readTop3k();
const support = {};
for (const combo of COMBOS) {
  let n = 0;
  for (const w of words) if (w.includes(combo)) n += 1;
  support[combo] = n;
}

const sorted = COMBOS.slice().sort((a, b) => support[a] - support[b]);
const dead = sorted.filter((c) => support[c] < MIN_SUPPORT);
const kept = COMBOS.filter((c) => support[c] >= MIN_SUPPORT);
const keptSupports = kept.map((c) => support[c]).sort((a, b) => a - b);
const q = (arr, p) => arr[Math.min(arr.length - 1, Math.floor(arr.length * p))];

console.log(`combo support vs the top ${words.length} common words`);
console.log('');
console.log(`BEFORE  ${COMBOS.length} combos`);
const allSupports = COMBOS.map((c) => support[c]).sort((a, b) => a - b);
console.log(
  `  support  p10 ${q(allSupports, 0.1)} · median ${q(allSupports, 0.5)} · p90 ${q(allSupports, 0.9)} · max ${allSupports[allSupports.length - 1]}`
);
console.log(`  under 10: ${allSupports.filter((s) => s < 10).length} · under 25: ${allSupports.filter((s) => s < 25).length}`);
console.log('');
console.log(`DROPPED ${dead.length} combos with support < ${MIN_SUPPORT}:`);
const bySupport = new Map();
for (const c of dead) bySupport.set(support[c], [...(bySupport.get(support[c]) || []), c]);
for (const [s, list] of [...bySupport.entries()].sort((a, b) => a[0] - b[0])) {
  console.log(`  support ${s}: ${list.join(' ')}`);
}
console.log('');
console.log(`AFTER   ${kept.length} combos`);
console.log(
  `  support  p10 ${q(keptSupports, 0.1)} · median ${q(keptSupports, 0.5)} · p90 ${q(keptSupports, 0.9)} · min ${keptSupports[0]}`
);

const out = {
  _note:
    'GENERATED by scripts/build-combo-support.js — do not hand-edit. support[combo] = how many of ' +
    'the 3000 words in data/top3k.txt contain that combo. `dropped` lists the combos removed for ' +
    'support < ' + MIN_SUPPORT + ' (kept for the record so a future run can see what went).',
  minSupport: MIN_SUPPORT,
  wordCount: words.length,
  dropped: dead.map((c) => ({ combo: c, support: support[c] })),
  support: Object.fromEntries(kept.map((c) => [c, support[c]])),
};

if (process.argv.includes('--dry')) {
  console.log('\n--dry: nothing written.');
} else {
  const dest = path.join(ROOT, 'comboSupport.json');
  fs.writeFileSync(dest, `${JSON.stringify(out, null, 2)}\n`);
  console.log(`\nwrote ${dest}`);
}
